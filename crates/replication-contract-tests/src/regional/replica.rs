use std::collections::BTreeMap;

use replication_provider::ordering::{
    clock::{CapturedClockPlan, ClockFloor},
    winner::{WinnerDecision, WinnerEffectPlan},
};
use replication_types::{
    event::{
        identity::{CanonicalEventId, CanonicalItemKey},
        order::HybridLogicalClock,
    },
    identity::origin::OriginId,
};

use super::event::{HarnessEvent, ItemMutation};
use crate::HarnessResult;

pub struct RegionalReplica {
    pub(super) origin: OriginId,
    pub(super) position: u64,
    pub(super) clock: ClockFloor,
    pub(super) history: BTreeMap<CanonicalEventId, HarnessEvent>,
    pub(super) winners: BTreeMap<CanonicalItemKey, HarnessEvent>,
    pub(super) materializations: Vec<HarnessEvent>,
}
impl RegionalReplica {
    pub fn new(region: &str) -> HarnessResult<Self> {
        Ok(Self {
            origin: OriginId {
                region: region.parse()?,
                database_group: [4; 16].try_into()?,
                journal_generation: 1.into(),
                journal_partition: 0.into(),
            },
            position: 0,
            clock: ClockFloor::Recovered(HybridLogicalClock {
                physical_ms: 0,
                logical: 0,
            }),
            history: BTreeMap::new(),
            winners: BTreeMap::new(),
            materializations: Vec::new(),
        })
    }
    pub fn write(&mut self, wall_ms: u64, value: Option<&[u8]>) -> HarnessResult<HarnessEvent> {
        self.write_item(
            wall_ms,
            ItemMutation {
                key: b"one-key",
                value,
            },
        )
    }
    pub fn write_item(
        &mut self,
        wall_ms: u64,
        item: ItemMutation<'_>,
    ) -> HarnessResult<HarnessEvent> {
        let clock = CapturedClockPlan {
            wall_ms,
            local: self.clock,
            received: None,
        }
        .issue_clock()?;
        let position = self
            .position
            .checked_add(1)
            .ok_or("origin position exhausted")?;
        let event = HarnessEvent::mutation(self.origin.clone(), position, clock, item)?;
        self.accept(event.clone())?;
        self.position = position;
        self.clock = ClockFloor::Recovered(clock);
        Ok(event)
    }
    pub fn accept(&mut self, event: HarnessEvent) -> HarnessResult<WinnerDecision> {
        event.validate()?;
        let id = event.winner.event.clone().ok_or("event identity missing")?;
        let known = self.history.get(&id);
        if known.is_some_and(|old| old != &event) {
            return Err("same identity changed content".into());
        }
        let decision = WinnerEffectPlan {
            incoming: &event.winner,
            observed: self.winners.get(&event.winner.key).map(|old| &old.winner),
            known_identity: known.map(|old| (id.clone(), old.winner.digest)),
        }
        .decide_winner()?;
        if let replication_types::event::order::WinnerOrder::Mutation { clock, .. } =
            event.winner.order
        {
            self.clock = CapturedClockPlan {
                wall_ms: 0,
                local: self.clock,
                received: None,
            }
            .observe_clock(clock);
        }
        if decision == WinnerDecision::Replace {
            self.winners.insert(event.winner.key.clone(), event.clone());
            self.materializations.push(event.clone());
        }
        self.history.entry(id).or_insert(event);
        Ok(decision)
    }
    pub fn history(&self) -> &BTreeMap<CanonicalEventId, HarnessEvent> {
        &self.history
    }
    pub fn winner(&self) -> Option<&HarnessEvent> {
        self.winners.values().next()
    }
    pub fn winners(&self) -> &BTreeMap<CanonicalItemKey, HarnessEvent> {
        &self.winners
    }
    /// Protected fixture image recovery: canonical replay restores winner/clock
    /// floors; the original regional stream remains persisted, rather than
    /// being regenerated by replay.
    pub fn restart(self) -> HarnessResult<Self> {
        let events: Vec<HarnessEvent> = serde_json::from_slice(&serde_json::to_vec(
            &self.history.values().collect::<Vec<_>>(),
        )?)?;
        let mut recovered = Self::new(self.origin.region.as_ref())?;
        for event in events {
            if let Some(CanonicalEventId::Origin(id)) = &event.winner.event
                && id.origin == recovered.origin
            {
                recovered.position = recovered.position.max(u64::from(id.position));
            }
            recovered.accept(event)?;
        }
        recovered.materializations = self.materializations;
        Ok(recovered)
    }
    pub fn regional_stream(&self) -> &[HarnessEvent] {
        &self.materializations
    }
}
